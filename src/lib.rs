/// Struct-level columnar packing with chunked serialization and optimized filtering.
///
/// Implemented by `#[derive(PcoPack)]`. Before serialization: sort by `timestamp`
/// field (if configured), group by `index` fields, then split each group into
/// chunks of at most `CHUNK_SIZE` rows.
pub trait PcoPack: PcoFilter + Sized {
    /// Maximum rows per chunk. Larger chunks improve compression but use more memory
    /// during columnar conversion.
    const CHUNK_SIZE: usize = 262_144;

    /// Decompression state for reading columnar data back into row structs.
    type Reader;

    /// Chunked struct with uncompressed metadata (index, timestamp bounds) and compressed payload columns.
    type Chunk: Clone + Serialize + for<'de> Deserialize<'de>;

    /// Typed filter struct generated by the derive macro.
    type Filter: TryInto<serde_json::Value>;

    fn serialize(data: Vec<Self>) -> Result<Vec<u8>> {
        Self::to_bytes(&PcoPack::write(data)?)
    }

    fn deserialize(bytes: &[u8]) -> Result<Vec<Self>> {
        PcoPack::read(Self::from_bytes(bytes)?)
    }

    fn write(data: Vec<Self>) -> Result<Vec<Self::Chunk>>;

    fn read(chunks: Vec<Self::Chunk>) -> Result<Vec<Self>>;

    fn to_bytes(chunks: &[Self::Chunk]) -> Result<Vec<u8>>;

    fn from_bytes(bytes: &[u8]) -> Result<Vec<Self::Chunk>>;

    fn filter<T>(chunks: &[Self::Chunk], query: T, fields: &[&str]) -> Result<Vec<Self>>
    where
        T: TryInto<serde_json::Value>,
        <T as TryInto<serde_json::Value>>::Error: Into<anyhow::Error>,
    {
        Self::filter_value(chunks, &query.try_into().map_err(Into::into)?, fields)
    }

    fn filter_bytes<T>(bytes: &[u8], query: T, fields: &[&str]) -> Result<Vec<Self>>
    where
        T: TryInto<serde_json::Value>,
        <T as TryInto<serde_json::Value>>::Error: Into<anyhow::Error>,
    {
        Self::filter(&Self::from_bytes(bytes)?, query, fields)
    }

    /// Internal method that takes a JSON value directly. Used by filter/filter_bytes after conversion.
    fn filter_value(chunks: &[Self::Chunk], query: &serde_json::Value, fields: &[&str]) -> Result<Vec<Self>>;

    /// Merge query-derived fields with explicitly requested fields, validating all are known.
    ///
    /// Extracts top-level field names from the JSON query (splitting on '.'), merges them
    /// with the user-provided `fields` list without duplicates, and validates that:
    /// - All query fields exist in this type's schema
    /// - No requested field contains a nested path ('.')
    /// - All requested fields exist in this type's schema
    fn resolve_fields(query: &serde_json::Value, fields: &[&str]) -> Result<Vec<&'static str>>;

    /// Typed view over a chunk's decompressed columns, passed to `Consumer` implementations.
    /// The derive generates one accessor per struct field.
    type Columns<'a>;

    /// Reconstruct the full row struct from a column view. Fields outside the loaded
    /// projection take their `Default` value.
    fn hydrate(columns: &mut Self::Columns<'_>, row: usize) -> Result<Self>;

    /// Wraps a decompressed reader in the column view. Generated code uses this to hand
    /// enum variant payload blocks to pattern-`fold!` consumers.
    fn columns(reader: &mut <Self as PcoSerde>::Reader) -> Self::Columns<'_>;

    /// Streaming fold engine behind `PcoPack::for_each`.
    fn fold_value<C>(
        chunks: &[Self::Chunk], query: &serde_json::Value, fields: &[&str], consumer: &mut C,
    ) -> Result<()>
    where
        C: Consumer<Self>;

    /// Streams every row matching the query into `consumer` without materializing a
    /// row vector.
    ///
    /// The loaded projection is `fields` plus `Consumer::FIELDS` plus the fields the
    /// query references; when all are empty every column loads, while a `fold!`
    /// projection loads only the columns its closure reads.
    ///
    /// The consumer may return `()` or `Result<()>`; a decode error or `Err` aborts
    /// the stream. Rows delivered before the abort are not rolled back; with index
    /// grouping, which rows those were depends on chunk storage order and is
    /// unspecified. Hydration closures that touch fields need an annotated parameter
    /// (`|row: Sensor|`): argument types are not inferred through the generic
    /// `Consumer` bound.
    fn for_each<C, T>(chunks: &[Self::Chunk], query: T, fields: &[&str], mut consumer: C) -> Result<()>
    where
        C: Consumer<Self>,
        T: TryInto<serde_json::Value>,
        <T as TryInto<serde_json::Value>>::Error: Into<anyhow::Error>,
    {
        Self::fold_value(chunks, &query.try_into().map_err(Into::into)?, fields, &mut consumer)
    }

    /// Like `for_each`, reading from a serialized blob.
    fn for_each_bytes<C, T>(bytes: &[u8], query: T, fields: &[&str], consumer: C) -> Result<()>
    where
        C: Consumer<Self>,
        T: TryInto<serde_json::Value>,
        <T as TryInto<serde_json::Value>>::Error: Into<anyhow::Error>,
    {
        Self::for_each(&Self::from_bytes(bytes)?, query, fields, consumer)
    }
}

/// Adapter letting `for_each` closures return either `()` or `Result<()>`.
pub trait Output {
    fn lift(self) -> Result<()>;
}

impl Output for () {
    fn lift(self) -> Result<()> {
        Ok(())
    }
}

impl<E: Into<anyhow::Error>> Output for std::result::Result<(), E> {
    fn lift(self) -> Result<()> {
        self.map_err(Into::into)
    }
}

/// Per-row sink for [`PcoPack::for_each`]: either a `|row: R|` closure over fully
/// hydrated rows, or a `fold!` projection that pops only its own columns. Wrapper
/// crates (e.g. persistence layers) can take `C: Consumer<R>` and forward it unchanged.
pub trait Consumer<R: PcoPack>: Sized {
    /// Field names this consumer reads. Empty (the default) requests nothing of its
    /// own, so the projection comes from `for_each`'s `fields` and the query.
    /// `fold!` struct folds list their column parameters; enum folds instead list
    /// variant names, one per arm. Wrappers can inspect this via `projection_fields`
    /// to push column selection into their own storage layer.
    const FIELDS: &'static [&'static str];

    /// Per-`FIELDS` flag set by `fold!` for arms that read their variant's payload
    /// slots (pattern or binding form). The engine gates the enum slot-streaming fast
    /// path on it and, in debug builds, cross-checks each flagged arm's slot cursor
    /// against its delivered row count. Empty (the default) marks a hand-written
    /// consumer: neither path applies.
    #[doc(hidden)]
    const POPS_PAYLOAD: &'static [bool] = &[];

    /// Called once per surviving row. Rows ascend within a chunk, and accessors must
    /// never see an index below a previously consumed row (columns are forward-only).
    /// Chunks are visited in stored order, which index grouping may reorder relative
    /// to the input. `Err` aborts the stream; delivered rows are not rolled back.
    fn consume(&mut self, columns: &mut R::Columns<'_>, row: usize) -> Result<()>;

    /// Called instead of `consume` for enum folds declaring multiple variants:
    /// `variant` is the matching arm's index within `FIELDS`, so a multi-arm `fold!`
    /// dispatches without ever seeing discriminant values. Default forwards to
    /// `consume`.
    fn consume_variant(&mut self, columns: &mut R::Columns<'_>, row: usize, _variant: usize) -> Result<()> {
        self.consume(columns, row)
    }
}

impl<R, F, O> Consumer<R> for F
where
    R: PcoPack,
    F: FnMut(R) -> O,
    O: Output,
{
    const FIELDS: &'static [&'static str] = &[];

    fn consume(&mut self, columns: &mut R::Columns<'_>, row: usize) -> Result<()> {
        let row = R::hydrate(columns, row)?;
        (self)(row).lift()
    }
}

/// Field names `C` reads, before query fields are merged. Lets persistence wrappers
/// build a narrowed SELECT list, then add query fields via [`PcoPack::resolve_fields`].
pub fn projection_fields<R: PcoPack, C: Consumer<R>>() -> &'static [&'static str] {
    C::FIELDS
}

/// Basic columnar write and read for a single type.
pub trait PcoSerde: Sized + Clone {
    type Writer: Default;
    type Reader: Clone;

    fn write(data: Vec<Self>, float_round: u32, time_round: chrono::Duration) -> Result<Vec<u8>>;

    /// Whether deep-cloning one value is a bounded shallow copy.
    ///
    /// Struct writes clone cheap columns into compact owned staging and
    /// stage expensive columns as references into the rows. Containers
    /// forward the element's answer, since cloning `Vec<String>` fans out
    /// per element. Expensive types override the default.
    const CHEAP_TO_CLONE: bool = true;

    /// Write a column over borrowed values. The default clones and
    /// delegates to `write`; expensive types override to encode from the
    /// references, which is what lets struct writes skip payload clones.
    fn write_borrowed(values: &[&Self], float_round: u32, time_round: chrono::Duration) -> Result<Vec<u8>> {
        let owned: Vec<Self> = values.iter().map(|v| (*v).clone()).collect();
        Self::write(owned, float_round, time_round)
    }

    fn read(src: &mut Cursor<&[u8]>, float_round: u32, time_round: chrono::Duration) -> Result<Self::Reader>;

    fn validate_bounds(reader: &mut Self::Reader) -> Result<Option<usize>>;

    /// Get the element at `index`. Iteration always moves forward (never backward),
    /// so lazy decompressors may advance their internal cursor without resetting.
    fn get(reader: &mut Self::Reader, index: usize) -> Result<Option<Self>>;
}

/// Fallback deserialization for types that need to read raw msgpack bytes directly.
/// Returns the same type as PcoSerde::read(), enabling fallback data to be used with
/// get() and validate_bounds() calls transparently.
pub trait FallbackReader {
    fn read_fallback(raw: &[u8]) -> anyhow::Result<Self>
    where
        Self: Sized;
}

/// Filter support for PcoSerde and PcoPack types.
pub trait PcoFilter: PcoSerde {
    fn filter_bulk(reader: &mut Self::Reader, field: usize, filter: &Filter, matches: &mut FilterMask) -> Result<()>;

    fn filter_nested(
        reader: &mut Self::Reader, path: &[usize], filter: &Filter, matches: &mut FilterMask,
    ) -> Result<()>;

    fn filter_match(value: &Self, filter: &Filter) -> bool;

    fn filter_step(reader: &mut Self::Reader, path: &[usize], filter: &Filter, matches: &mut FilterMask) -> Result<()> {
        if path.len() > 1 {
            Self::filter_nested(reader, path, filter, matches)
        } else {
            Self::filter_bulk(reader, path[0], filter, matches)
        }
    }

    fn resolve_filter(path: &str, json: &serde_json::Value) -> Result<ResolvedFilter>;

    fn resolve_query(query: &serde_json::Value) -> Result<Vec<ResolvedFilter>> {
        match query {
            serde_json::Value::Object(map) => {
                let mut plans = Vec::with_capacity(map.len());
                for (field_name, raw_value) in map {
                    let plan = Self::resolve_filter(field_name, raw_value).map_err(|err| {
                        if field_name.is_empty() {
                            anyhow::anyhow!("{err}")
                        } else {
                            anyhow::anyhow!("Failed to resolve filter for field '{field_name}': {err}")
                        }
                    })?;
                    plans.push(plan);
                }
                plans.iter_mut().for_each(|p| p.filter.normalize());
                Ok(plans)
            }
            _ => Err(::anyhow::anyhow!("Query must be a JSON object with field-name keys")),
        }
    }
}

/// Human-readable name of a JSON value's type, for filter error messages.
pub fn json_type_name(v: &serde_json::Value) -> &'static str {
    match v {
        serde_json::Value::Null => "null",
        serde_json::Value::Number(_) => "number",
        serde_json::Value::String(_) => "string",
        serde_json::Value::Bool(_) => "boolean",
        serde_json::Value::Array(_) => "array",
        serde_json::Value::Object(_) => "object",
    }
}

/// A resolved filter with an absolute path down the struct tree.
///
/// Produced by `PcoFilter::resolve_filter`.
#[derive(Clone, Debug)]
pub struct ResolvedFilter {
    /// Maps the user-provided string to fast numeric indexes ("a.b" -> [0, 2]).
    pub path: Vec<usize>,
    /// Filter value resolved to the correct data type to avoid type conversions in the hot loop.
    pub filter: Filter,
}

#[derive(Clone, Debug)]
pub enum Filter {
    I64(i64),
    F64(f64),
    String(String),
    Uuid(::uuid::Uuid),
    Bool(bool),
    Json(serde_json::Value),
    Bytes(Vec<u8>),
    Range(RangeInclusive<i64>),
    FloatRange(RangeInclusive<f64>),
    InclusionI64(ahash::HashSet<i64>),
    InclusionF64(Vec<f64>),
    InclusionString(ahash::HashSet<String>),
    InclusionUuid(ahash::HashSet<::uuid::Uuid>),
    InclusionBool(ahash::HashSet<bool>),
}

impl Filter {
    /// Downgrade single-element filters to exact matches for faster hot-loop comparison.
    fn normalize(&mut self) {
        match self {
            Filter::Range(r) if r.start() == r.end() => {
                *self = Filter::I64(*r.start());
            }
            Filter::FloatRange(r) if r.start() == r.end() => {
                *self = Filter::F64(*r.start());
            }
            Filter::InclusionI64(v) if v.len() == 1 => {
                let x = *v.iter().next().unwrap();
                *self = Filter::I64(x);
            }
            Filter::InclusionF64(v) if v.len() == 1 => {
                let x = v.remove(0);
                *self = Filter::F64(x);
            }
            Filter::InclusionString(v) if v.len() == 1 => {
                let x = v.iter().next().unwrap().clone();
                *self = Filter::String(x);
            }
            Filter::InclusionUuid(v) if v.len() == 1 => {
                let u = *v.iter().next().unwrap();
                *self = Filter::Uuid(u);
            }
            Filter::InclusionBool(v) if v.len() == 1 => {
                let b = *v.iter().next().unwrap();
                *self = Filter::Bool(b);
            }
            _ => {}
        }
    }
}

/// Dispatch trait for `Vec<T>`, serializing inner elements via `T::write()`
/// for optimal per-field compression.
pub trait VecPackable: PcoSerde {
    type VecWriter: Default;
    type VecReader;

    fn pack_vec(data: Vec<Self>, writer: &mut Self::VecWriter);

    fn write_vec(
        writer: Self::VecWriter, float_round: u32, time_round: chrono::Duration, out: &mut Vec<u8>,
    ) -> Result<()>;

    fn read_vec(src: &mut Cursor<&[u8]>, float_round: u32, time_round: chrono::Duration) -> Result<Self::VecReader>;

    fn validate_vec_bounds(reader: &Self::VecReader) -> Result<Option<usize>>;

    fn get_vec(reader: &mut Self::VecReader, index: usize) -> Result<Option<Vec<Self>>>;

    fn filter_vec(reader: &Self::VecReader, filter: &Filter, matches: &mut FilterMask) -> Result<()>;

    fn filter_vec_nested(
        reader: &mut Self::VecReader, path: &[usize], filter: &Filter, matches: &mut FilterMask,
    ) -> Result<()>;

    fn filter_vec_match(value: &Self, filter: &Filter) -> bool;
}
